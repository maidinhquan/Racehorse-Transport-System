import { afterEach, expect, test, vi } from "vitest";
import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter, Routes, Route } from "react-router-dom";
import { relational, type Request, type Contract } from "./api";
import ContractPage from "../../user-dashboard/page/transport-request-page/contract/ContractPage";
vi.mock("../api", async original => ({ ...await original<object>(), get: vi.fn().mockResolvedValue([]) }));
afterEach(() => vi.restoreAllMocks());
const horse = { horseId: "owned", name: "SQL horse", version: "hv", hasDocuments: true, selectable: true };
const row = { requestId: "real", version: "rv", customerName: "SQL Customer", departure: "API A", destination: "API B", status: "ACCEPTED", horses: [horse], preparationDays: 2, departureAt: "2026-11-20T00:00:00Z", deliveryAt: "2026-11-22T00:00:00Z", contracts: [], input: { trip: { pickup: { country: "VN" }, delivery: { country: "VN" } } } } as unknown as Request;
const c = { contractId: "sql-contract", version: "cv", status: "SIGNED", isCurrent: true, relationalTermsReady: true, hasAcceptanceEvidence: true, totalPrice: 100000000, depositAmount: 40000000, currency: "VND", paidAmount: 0, payments: [], signDeadline: "2026-11-01T10:00:00Z", signedAt: "2026-10-20T10:00:00Z" } as unknown as Contract;
test("contract opens authenticated PDF in new tab, sends OTP, refreshes version and signs before offering payment", async () => {
  const pending = { ...c, status: "PENDING_SIGNATURE", hasAcceptanceEvidence: false, signedAt: null, pdfSha256: "pdf-hash", version: "before-otp" };
  const next = { ...row, contracts: [{ ...pending, version: "after-otp" }] };
  vi.spyOn(relational, "detail").mockResolvedValueOnce({ ...row, contracts: [pending] }).mockResolvedValueOnce(next).mockResolvedValueOnce({ ...row, contracts: [{ ...c, pdfSha256: "pdf-hash" }] });
  const tab = { opener: {}, location: { href: "about:blank" }, close: vi.fn() };
  vi.spyOn(window, "open").mockReturnValue(tab as unknown as Window);
  vi.spyOn(relational, "pdfUrl").mockResolvedValue("blob:private-pdf");
  const revoke = vi.fn(); vi.stubGlobal("URL", Object.assign(URL, { revokeObjectURL: revoke }));
  const action = vi.spyOn(relational, "action").mockResolvedValue({ sent: true });
  render(<MemoryRouter initialEntries={["/customer/requests/real/contract"]}><Routes><Route path="/customer/requests/:requestId/contract" element={<ContractPage />} /></Routes></MemoryRouter>);
  await screen.findByText("sql-contract");
  await userEvent.click(screen.getByRole("checkbox"));
  expect(screen.getByRole("button", { name: "Gửi OTP" })).toBeDisabled();
  await userEvent.click(screen.getByRole("button", { name: "Xem full hợp đồng" }));
  await waitFor(() => expect(tab.location.href).toBe("blob:private-pdf"));
  expect(tab.opener).toBeNull();
  await userEvent.click(screen.getByRole("button", { name: "Gửi OTP" }));
  await screen.findByText(/Đã gửi OTP/);
  expect(action).toHaveBeenNthCalledWith(1, "/customer/contracts/sql-contract/otp", { version: "before-otp", pdfSha256: "pdf-hash" });
  await userEvent.type(screen.getByLabelText("Mã OTP"), "123456");
  await userEvent.click(screen.getByRole("button", { name: "Sign Contract" }));
  await screen.findByText("Contract signed successfully.");
  expect(action).toHaveBeenNthCalledWith(2, "/customer/contracts/sql-contract/sign", { version: "after-otp", pdfSha256: "pdf-hash", otp: "123456" });
  expect(screen.queryByRole("button", { name: "Sign Contract" })).not.toBeInTheDocument();
});

test("failed PDF download leaves OTP disabled and closes the blank tab", async () => {
  vi.spyOn(relational, "detail").mockResolvedValue({ ...row, contracts: [{ ...c, status: "PENDING_SIGNATURE", hasAcceptanceEvidence: false, signedAt: null, pdfSha256: "pdf-hash" }] });
  const tab = { opener: {}, close: vi.fn() };
  vi.spyOn(window, "open").mockReturnValue(tab as unknown as Window);
  vi.spyOn(relational, "pdfUrl").mockRejectedValue(new Error("PDF unavailable"));
  const action = vi.spyOn(relational, "action");
  render(<MemoryRouter initialEntries={["/customer/requests/real/contract"]}><Routes><Route path="/customer/requests/:requestId/contract" element={<ContractPage />} /></Routes></MemoryRouter>);
  await screen.findByText("sql-contract"); await userEvent.click(screen.getByRole("checkbox"));
  await userEvent.click(screen.getByRole("button", { name: "Xem full hợp đồng" }));
  await waitFor(() => expect(tab.close).toHaveBeenCalled());
  expect(screen.getByRole("button", { name: "Gửi OTP" })).toBeDisabled();
  expect(action).not.toHaveBeenCalled();
});
