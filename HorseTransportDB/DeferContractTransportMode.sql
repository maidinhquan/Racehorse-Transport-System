-- Run against the existing Reviewed database. Published snapshots and business rows are preserved.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('dbo.TRANSPORT_REQUEST', 'U') IS NULL
    THROW 51000, 'The Reviewed TRANSPORT_REQUEST table is required.', 1;
IF OBJECT_ID('dbo.CK_F1S_TRANSPORT_REQUEST_Route', 'C') IS NOT NULL
    ALTER TABLE dbo.TRANSPORT_REQUEST DROP CONSTRAINT CK_F1S_TRANSPORT_REQUEST_Route;
ALTER TABLE dbo.TRANSPORT_REQUEST WITH CHECK ADD CONSTRAINT CK_F1S_TRANSPORT_REQUEST_Route
    CHECK ((OriginCountry IS NULL AND DestinationCountry IS NULL)
        OR (OriginCountry IS NOT NULL AND DestinationCountry IS NOT NULL));
COMMIT TRANSACTION;
