-- 4. Bảng bảo hiểm chuyến đi (TRIP_INSURANCE)
IF OBJECT_ID('dbo.TRIP_INSURANCE') IS NULL
BEGIN
    CREATE TABLE dbo.[TRIP_INSURANCE] (
        InsuranceID VARCHAR(50) NOT NULL CONSTRAINT PK_TripInsurance PRIMARY KEY,
        TripID VARCHAR(50) NOT NULL CONSTRAINT FK_Insurance_Trip REFERENCES TRIP_PLAN(TripID),
        Insurer NVARCHAR(150) NOT NULL,
        PolicyNumber VARCHAR(100) NOT NULL,
        CoverageAmount DECIMAL(18, 0) NOT NULL,
        ValidFrom DATE NOT NULL,
        ValidTo DATE NOT NULL,
        Status VARCHAR(50) NOT NULL CONSTRAINT DF_Insurance_Status DEFAULT 'PENDING',
        CheckedBy VARCHAR(50) NULL CONSTRAINT FK_Insurance_CheckedBy REFERENCES [USER](UserID),
        CheckedAtUtc DATETIME2(7) NULL,
        CreatedAtUtc DATETIME2(7) NOT NULL CONSTRAINT DF_Insurance_CreatedAt DEFAULT SYSUTCDATETIME()
    );
END
GO

-- 5. Bảng yêu cầu bổ sung giấy tờ (DOCUMENT_REQUEST)
IF OBJECT_ID('dbo.DOCUMENT_REQUEST') IS NULL
BEGIN
    CREATE TABLE dbo.[DOCUMENT_REQUEST] (
        RequestDocID VARCHAR(50) NOT NULL CONSTRAINT PK_DocumentRequest PRIMARY KEY,
        TripID VARCHAR(50) NOT NULL CONSTRAINT FK_DocReq_Trip REFERENCES TRIP_PLAN(TripID),
        RequestID VARCHAR(50) NOT NULL CONSTRAINT FK_DocReq_Request REFERENCES TRANSPORT_REQUEST(RequestID),
        KeyName VARCHAR(50) NOT NULL,
        Scope VARCHAR(50) NOT NULL,
        Reason NVARCHAR(1000) NOT NULL,
        DueAt DATE NULL,
        Status VARCHAR(50) NOT NULL CONSTRAINT DF_DocReq_Status DEFAULT 'OPEN',
        CreatedBy VARCHAR(50) NOT NULL CONSTRAINT FK_DocReq_CreatedBy REFERENCES [USER](UserID),
        CreatedAtUtc DATETIME2(7) NOT NULL CONSTRAINT DF_DocReq_CreatedAt DEFAULT SYSUTCDATETIME(),
        FulfilledAtUtc DATETIME2(7) NULL
    );
END
GO

-- 6. Bảng lưu bộ quy định áp dụng cho chuyến (TRIP_REQUIREMENT_SET)
IF OBJECT_ID('dbo.TRIP_REQUIREMENT_SET') IS NULL
BEGIN
    CREATE TABLE dbo.[TRIP_REQUIREMENT_SET] (
        SnapshotID VARCHAR(50) NOT NULL CONSTRAINT PK_TripRequirementSet PRIMARY KEY,
        TripID VARCHAR(50) NOT NULL CONSTRAINT FK_ReqSet_Trip REFERENCES TRIP_PLAN(TripID),
        PkgId VARCHAR(50) NOT NULL,
        PkgVersion INT NOT NULL CONSTRAINT DF_ReqSet_PkgV DEFAULT 1,
        PkgName NVARCHAR(200) NOT NULL,
        AppliedBy VARCHAR(50) NOT NULL CONSTRAINT FK_ReqSet_AppliedBy REFERENCES [USER](UserID),
        AppliedAtUtc DATETIME2(7) NOT NULL CONSTRAINT DF_ReqSet_AppliedAt DEFAULT SYSUTCDATETIME(),
        SnapshotJson NVARCHAR(MAX) NULL
    );
END
GO

-- 7. Bảng kiểm tra lộ trình trạm kiểm dịch (TRIP_CHECKPOINT_CLEARANCE)
IF OBJECT_ID('dbo.TRIP_CHECKPOINT_CLEARANCE') IS NULL
