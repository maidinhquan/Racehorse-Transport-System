    CREATE TABLE dbo.[TRIP_CHECKPOINT_CLEARANCE] (
        ClearanceID VARCHAR(50) NOT NULL CONSTRAINT PK_CheckpointClearance PRIMARY KEY,
        TripID VARCHAR(50) NOT NULL CONSTRAINT FK_Clearance_Trip REFERENCES TRIP_PLAN(TripID),
        CheckpointIndex INT NOT NULL,
