using Microsoft.OpenApi.Models;
using Swashbuckle.AspNetCore.SwaggerGen;

namespace WebApi.Extensions;

// Applies only to the rebuilt module; authentication documentation is unchanged.
public sealed class Flow1SwaggerExamples : IOperationFilter
{
    public void Apply(OpenApiOperation operation, OperationFilterContext context)
    {
        if (context.MethodInfo.DeclaringType?.Namespace != "WebApi.Controllers.Flow1") return;
        var path = context.ApiDescription.RelativePath ?? "";
        operation.Tags = [new OpenApiTag { Name = "Flow1 / " + context.MethodInfo.DeclaringType.Name.Replace("Controller", "") }];
        operation.Description = "Flow 1 Reviewed backend. IDs are generated by SQL defaults; versionNo identifies a contract edition. " +
            "No RowVersion/concurrency token is required. Amounts are whole VND. Business policies resolve destination COUNTRY, then TRANSPORT_MODE, then GLOBAL. " +
            "Unavailable persisted fields are null and listed in unsupportedFields. Timestamps use UTC.";
        if (path.Contains("contract", StringComparison.OrdinalIgnoreCase))
            operation.Description += " Each published edition keeps its immutable snapshot and private PDF. Accept terms, receive a verified VNPAY deposit, then request a version-bound OTP. Signing atomically activates one planning Trip. Current deadline extensions are metadata; they do not rewrite the published snapshot.";
        if (path.Contains("payment", StringComparison.OrdinalIgnoreCase) || path.Contains("deposit", StringComparison.OrdinalIgnoreCase))
            operation.Description += " Only a verified VNPAY IPN credits the invoice. Browser return, session creation and Manager actions cannot confirm payment. Late or inconsistent verified receipts require reconciliation.";
        if (path.EndsWith("customer/requests", StringComparison.OrdinalIgnoreCase) && context.ApiDescription.HttpMethod == "POST")
            operation.Parameters.Add(new OpenApiParameter { Name = "Idempotency-Key", In = ParameterLocation.Header, Required = true,
                Description = "UUID retained when retrying the same create operation. Never generate a new key solely because of a timeout.",
                Schema = new OpenApiSchema { Type = "string", Format = "uuid" } });
        foreach (var status in new[] { "400", "401", "403", "404", "409", "429", "500", "503" })
            if (!operation.Responses.ContainsKey(status)) operation.Responses[status] = new OpenApiResponse { Description = status == "503" ? "Required database or external service is unavailable/unconfigured." : "Error envelope: success=false, message, errorCode, data=null." };
    }
}
